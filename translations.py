def get_translator(language: str):
    """Returns a t(key) function bound to the given language, falling back
    to English for any missing key so the UI never shows a raw key name."""
    lang_dict = TRANSLATIONS.get(language, TRANSLATIONS["English"])
    english_dict = TRANSLATIONS["English"]

    def t(key: str) -> str:
        return lang_dict.get(key, english_dict.get(key, key))

    return t
